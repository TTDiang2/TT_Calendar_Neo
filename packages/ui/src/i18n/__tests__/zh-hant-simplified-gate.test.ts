import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const DICT_PATH = fileURLToPath(new URL('../dict/zh-Hant.ts', import.meta.url))

// 简体独有字形抽样（覆盖本次翻译产出的高频用字域）：
// 们设让说记图历动边进行后处复关涵盖权确认标签丝级变实际层网络记号
// 贮汇账号丝园图场坛采用银钱铁门问间阅队际随隐形页预风飞饭馆马验龄
const SIMPLIFIED_MARKERS = [
  '们', '设', '让', '说', '记', '图', '历', '动', '边', '进', '处', '复', '关', '盖', '权',
  '确', '丝', '级', '变', '实', '层', '网', '络', '贮', '汇', '账', '号', '园', '场', '坛',
  '采', '银', '钱', '铁', '门', '问', '间', '阅', '队', '际', '随', '页', '预', '风',
  '飞', '饭', '馆', '马', '验', '龄', '应', '当', '归', '针', '钟', '钥', '钢', '铜', '银',
  '条', '东', '两', '业', '节', '农', '艺', '药', '华', '毕', '报', '护', '张', '读', '课', '级', '红', '纯', '纸', '纹', '纺', '组', '终', '经', '统', '继', '绩', '维', '绿', '缓', '编', '缘', '举', '义', '乐', '习', '乡', '书', '买', '乱', '亏', '亿', '从',
  '众', '优', '会', '伞', '伟', '传', '估', '佣', '侦', '伪', '体', '余', '诱', '语', '误',
  '读', '谁', '课', '调', '谅', '谈', '谊', '谢', '贞', '负', '货', '质', '贴', '贵', '买',
  '费', '赋', '赠', '赵', '赶', '趋', '转', '辑', '辞', '迁', '达', '违', '运', '还', '这',
  '远', '连', '迟', '适', '选', '逊', '递', '逻', '遗', '邓', '邮', '邻', '郑', '释', '雏',
  '雾', '静', '顶', '顾', '颂', '标', '签', '涂', '优', '击', '双', '据', '绩', '务', '动',
]

describe('zh-Hant 简体字混入门禁', () => {
  const source = readFileSync(DICT_PATH, 'utf8')

  it('字典中不出现简体独有字形', () => {
    const hits: string[] = []
    for (const ch of SIMPLIFIED_MARKERS) {
      if (source.includes(ch)) hits.push(ch)
    }
    expect(hits, `发现简体字形：${hits.join(' ')}（行内定位见失败输出）`).toEqual([])
  })

  it('抽样正体字存在（门禁自身有效性：字典不是空的/全英文）', () => {
    for (const ch of ['設定', '儲存', '資料', '圖層', '待辦', '倒數日']) {
      expect(source.includes(ch), `缺少正体词：${ch}`).toBe(true)
    }
  })
})
